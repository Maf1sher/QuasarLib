package mafisher.quasar.client.effect;

/** The fluid medium surrounding the camera or an effect. */
public enum ScreenEffectMedium {
    /** Air or another non-fogging medium. */
    NONE,
    /** Water, including waterlogged blocks. */
    WATER,
    /** Lava. */
    LAVA,
    /** Powder snow. */
    POWDER_SNOW
}
